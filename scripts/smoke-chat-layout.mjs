import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
const source = fs.readFileSync('js/chat-layout.js', 'utf8');
function measure({phone=false, height=800, keyboard=0, work=900, banner=0, focused=false, visible=true}={}) {
  const props = {}, events = {}, inputEvents = {}, vvEvents = {};
  const classes = () => ({toggle(k,v) { this[k]=v; }});
  const box = h => ({getBoundingClientRect:()=>({height:h,top:160})});
  const input = {style:{},addEventListener:(k,v)=>inputEvents[k]=v};
  const panel = {hidden:!visible}, scroller = {scrollTop:0,scrollHeight:2000};
  const nodes = {'.page':{style:{setProperty:(k,v)=>props[k]=parseFloat(v),removeProperty:k=>delete props[k]}},'.chat-scroll':scroller,'.chat-dock':box(150),'.chat-shell':box(640),'.pwa-install-banner':{...box(banner),hidden:!banner}};
  const doc = {body:{classList:classes(),scrollTop:0},documentElement:{classList:classes(),scrollTop:0},activeElement:focused?input:null,querySelector:k=>nodes[k],getElementById:k=>k==='panel-chat'?panel:k==='chat-input'?input:null};
  const win = {innerWidth:phone?390:1280,innerHeight:height,outerHeight:height+80,scrollX:0,scrollY:0,scrollTo(){this.scrollY=0;},screenY:0,screen:{availTop:0,availHeight:work},visualViewport:{width:phone?390:1280,height:height-keyboard,offsetTop:0,offsetLeft:0,addEventListener:(k,v)=>vvEvents[k]=v},matchMedia:q=>({matches:q.includes('max-width')?phone:!phone}),getComputedStyle:()=>({bottom:'0'}),addEventListener:(k,v)=>events[k]=v,requestAnimationFrame:fn=>fn()};
  vm.runInNewContext(source,{window:win,document:doc,MutationObserver:class {observe(){}},setTimeout:fn=>fn()});
  return {props,doc,win,input,inputEvents,vvEvents,events,scroller};
}
assert.equal(measure().props['--chat-room-height'],624);
assert.equal(measure({height:650}).props['--chat-room-height'],474);
assert.equal(measure({work:820}).props['--chat-room-height'],564);
assert.equal(measure({banner:80}).props['--chat-room-height'],544);
assert.equal(measure().props['--chat-dock-height'],150);
assert.equal(measure({focused:true}).doc.body.classList['chat-keyboard-open'],undefined);
assert.equal(measure({phone:true,keyboard:300,visible:false}).props['--chat-room-height'],340);
const locked = measure({phone:true,height:844,keyboard:364,focused:true});
assert.equal(locked.props['--chat-room-height'],480);
assert.equal(locked.props['--chat-vv-height'],480);
assert.equal(locked.props['--chat-vv-width'],390);
assert.equal(locked.props['--chat-viewport-inset'],0);
assert.equal(locked.doc.body.classList['chat-keyboard-open'],true);
assert.equal(locked.scroller.scrollTop,2000);
locked.win.scrollY=100;
locked.events.scroll();
assert.equal(locked.win.scrollY,0);
locked.doc.activeElement=null;
locked.inputEvents.blur();
assert.equal(locked.doc.body.classList['chat-keyboard-open'],true);
locked.win.visualViewport.height=844;
locked.vvEvents.resize();
assert.equal(locked.doc.body.classList['chat-keyboard-open'],false);
assert.equal(locked.doc.documentElement.classList['chat-keyboard-open'],false);
for (const key of ['top','left','width','height']) assert.equal(locked.props['--chat-vv-'+key],undefined);
assert.equal(locked.props['--chat-room-height'],684);
console.log('Chat viewport/work-area/keyboard lock/unlock/banner smoke passed');
